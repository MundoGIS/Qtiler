import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import express from 'express';
import sharp from 'sharp';
import { registerQtilerSettingsRoutes } from '../routes/qtilerSettings.js';

test('branding endpoints enforce admin access, persist settings and validate logo content', async (context) => {
  const dataDir = await fs.mkdtemp(path.join(os.tmpdir(), 'qtiler-branding-test-'));
  const app = express();
  app.set('views', path.resolve('views'));
  app.set('view engine', 'ejs');
  app.use(express.json());
  app.use((req, _res, next) => { if (req.headers['x-test-role']) req.user = { role: req.headers['x-test-role'] }; next(); });
  registerQtilerSettingsRoutes({ app, requireAdmin: (_req, _res, next) => next(), dataDir });
  app.get('/admin', (req, res) => res.render('admin', { pageLang: 'en', proj4Presets: {}, assetVersion: 'test', user: req.user, authEnabled: true }));
  const server = app.listen(0, '127.0.0.1');
  await new Promise((resolve) => server.once('listening', resolve));
  context.after(async () => { await new Promise((resolve) => server.close(resolve)); await fs.rm(dataDir, { recursive: true, force: true }); });
  const url = `http://127.0.0.1:${server.address().port}`;
  assert.equal((await fetch(url + '/admin/qtiler-settings')).status, 401);
  assert.equal((await fetch(url + '/admin/qtiler-settings', { headers: { 'x-test-role': 'authenticated' } })).status, 403);
  const headers = { 'x-test-role': 'admin', 'content-type': 'application/json' };
  assert.equal((await fetch(url + '/admin/qtiler-settings', { method: 'PATCH', headers, body: JSON.stringify({ companyName: 'Example company', headerColor: '#005f73', footerText: 'Company information' }) })).status, 200);
  const saved = await (await fetch(url + '/admin/qtiler-settings', { headers })).json();
  assert.equal(saved.companyName, 'Example company');
  assert.equal(saved.headerTextColor, '#ffffff');
  assert.equal(JSON.parse(await fs.readFile(path.join(dataDir, 'qtiler-settings', 'settings.json'), 'utf8')).headerColor, '#005f73');
  assert.equal((await fetch(url + '/admin/qtiler-settings', { method: 'PATCH', headers, body: JSON.stringify({ footerWebsiteUrl: 'javascript:alert(1)' }) })).status, 400);
  assert.equal((await fetch(url + '/admin/qtiler-settings', { method: 'PATCH', headers, body: JSON.stringify({ footerText: '<script>alert(1)</script>', headerColor: '#ffffff' }) })).status, 200);
  const rendered = await (await fetch(url + '/admin', { headers })).text();
  assert.ok(rendered.includes('background:#ffffff'));
  assert.ok(rendered.includes('alt="Example company"'));
  assert.ok(rendered.includes('&lt;script&gt;alert(1)&lt;/script&gt;'));
  assert.ok(!rendered.includes('<script>alert(1)</script>'));
  assert.ok(rendered.includes('Qtiler settings'));
  assert.equal((await (await fetch(url + '/admin/qtiler-settings', { headers })).json()).headerTextColor, '#000000');
  const invalid = new FormData();
  invalid.append('logo', new Blob(['<svg onload="alert(1)"></svg>'], { type: 'image/svg+xml' }), 'logo.svg');
  assert.equal((await fetch(url + '/admin/qtiler-settings/logo', { method: 'POST', headers: { 'x-test-role': 'admin' }, body: invalid })).status, 400);
  const png = await sharp({ create: { width: 20, height: 20, channels: 4, background: '#005f73' } }).png().toBuffer();
  const valid = new FormData();
  valid.append('logo', new Blob([png], { type: 'image/png' }), 'logo.png');
  const uploaded = await fetch(url + '/admin/qtiler-settings/logo', { method: 'POST', headers: { 'x-test-role': 'admin' }, body: valid });
  assert.equal(uploaded.status, 200);
  const logo = await uploaded.json();
  assert.match(logo.logoUrl, /^\/qtiler-settings\/logo\/[a-f0-9]{64}\.png$/);
  assert.equal((await fetch(url + logo.logoUrl)).status, 200);
  assert.equal((await fetch(url + '/admin/qtiler-settings/logo', { method: 'DELETE', headers })).status, 200);
});